"""
Виртуальная потенциальная температура.

Влажный воздух легче сухого из-за меньшей молярной массы H2O.
Учёт — через виртуальную температуру:
    theta_v = theta * (1 + Rv/Rd * qv) / (1 + qv)
где Rv/Rd = 1.608, qv — удельная влажность.

Источник: ICON, mo_solve_nonhydro.f90, mo_nh_moist_thdyn.f90.
"""
import numpy as np


RV_OVER_RD = 1.608  # отношение газовых постоянных водяного пара и сухого воздуха


def virtual_theta(theta, qv):
    """
    Виртуальная потенциальная температура.

    Параметры
    ---------
    theta : (nlev, ...) или скаляр
        потенциальная температура сухого воздуха, К
    qv : (nlev, ...) или скаляр
        удельная влажность (кг пара / кг воздуха), безразмерная

    Возвращает
    ----------
    theta_v : той же формы
        виртуальная потенциальная температура, К
    """
    return theta * (1.0 + RV_OVER_RD * qv) / (1.0 + qv)


def virtual_theta_approx(theta, qv):
    """
    Приближённая формула (линеаризованная):
        theta_v ~ theta * (1 + 0.608 * qv)

    Используется, когда qv мало (< 0.02) и нужна скорость.
    Точность ~0.1% при qv = 0.02.
    """
    return theta * (1.0 + 0.608 * qv)